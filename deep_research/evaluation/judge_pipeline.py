"""Judge evaluation pipeline for scoring saved reports.

Orchestrates multi-judge evaluation of all reports generated by the
execution pipeline, with checkpoint/resume support.
"""

import asyncio
import json
import time
import structlog
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Optional

from deep_research.evaluation.multi_judge import (
    MultiJudge,
    JudgeConfig,
    EnsembleResult,
    JudgePassResult,
    CriterionVerdict,
)
from deep_research.evaluation.rubric_v2 import RubricV2
from deep_research.evaluation.execution_pipeline import ExecutionPipeline

logger = structlog.get_logger()


@dataclass
class JudgeProgress:
    """Progress tracking for judge pipeline."""
    total: int
    completed: int = 0
    start_time: float = 0.0

    @property
    def remaining(self) -> int:
        return self.total - self.completed

    @property
    def elapsed_minutes(self) -> float:
        return (time.time() - self.start_time) / 60 if self.start_time else 0

    def summary(self) -> str:
        return f"Judge: {self.completed}/{self.total} [{self.elapsed_minutes:.1f}m elapsed]"


class JudgePipeline:
    """Orchestrates multi-judge evaluation of reports."""

    def __init__(
        self,
        multi_judge: MultiJudge,
        reports_dir: Path,
        output_dir: Path,
        log_interval: int = 5,
    ):
        self.multi_judge = multi_judge
        self.reports_dir = reports_dir
        self.output_dir = output_dir
        self.log_interval = log_interval

        self.output_dir.mkdir(parents=True, exist_ok=True)

    def _verdict_path(self, pattern: str, query_id: str) -> Path:
        return self.output_dir / "verdicts" / pattern / f"{query_id}.json"

    def is_scored(self, pattern: str, query_id: str) -> bool:
        return self._verdict_path(pattern, query_id).exists()

    def _load_report(self, pattern: str, query_id: str) -> Optional[str]:
        """Load report text from the reports directory."""
        report_path = self.reports_dir / "reports" / pattern / f"{query_id}.md"
        if report_path.exists():
            return report_path.read_text()
        return None

    async def score_report(
        self,
        pattern: str,
        query_id: str,
        query_text: str,
        report_text: str,
        rubric: RubricV2,
    ) -> EnsembleResult:
        """Score a single report with the multi-judge ensemble."""
        result = await self.multi_judge.evaluate(
            query_id=query_id,
            query_text=query_text,
            pattern_name=pattern,
            report_text=report_text,
            rubric=rubric,
        )

        # Save verdict
        vp = self._verdict_path(pattern, query_id)
        vp.parent.mkdir(parents=True, exist_ok=True)
        vp.write_text(json.dumps(asdict(result), indent=2, default=str))

        return result

    async def score_all(
        self,
        queries: list,  # list[EvalQuery] — duck-typed: needs .id, .query, .rubric
        patterns: list[str] | None = None,
        resume: bool = True,
    ) -> list[EnsembleResult]:
        """Score all reports with multi-judge ensemble.

        Only scores reports that exist (have been generated by ExecutionPipeline).
        """
        patterns = patterns or ExecutionPipeline.PATTERN_NAMES

        # Save judge-specific environment metadata
        from deep_research.config import get_environment_metadata
        env_meta = get_environment_metadata()
        env_meta["judge_configs"] = [
            {"label": jc.label, "model": jc.model, "temperature": jc.temperature, "api_version": jc.api_version}
            for jc in self.multi_judge.judges
        ]
        env_path = self.output_dir / "judge_environment.json"
        env_path.write_text(json.dumps(env_meta, indent=2))

        # Build scoring plan
        to_score: list[tuple[str, object, str]] = []  # (pattern, query, report_text)
        for pattern in patterns:
            for query in queries:
                if resume and self.is_scored(pattern, query.id):
                    continue
                report_text = self._load_report(pattern, query.id)
                if report_text:
                    to_score.append((pattern, query, report_text))

        progress = JudgeProgress(total=len(to_score), start_time=time.time())

        logger.info("judge_pipeline_start", total=len(to_score))

        results: list[EnsembleResult] = []
        for i, (pattern, query, report_text) in enumerate(to_score):
            try:
                result = await self.score_report(
                    pattern=pattern,
                    query_id=query.id,
                    query_text=query.query,
                    report_text=report_text,
                    rubric=query.rubric,
                )
                results.append(result)
            except Exception as e:
                logger.error(
                    "judge_failed",
                    pattern=pattern,
                    query_id=query.id,
                    error=str(e)[:200],
                )

            progress.completed += 1
            if (i + 1) % self.log_interval == 0:
                logger.info("judge_progress", msg=progress.summary())

        # Save summary
        self._save_summary(results)

        return results

    def _save_summary(self, results: list[EnsembleResult]) -> None:
        """Save judge evaluation summary."""
        summary: dict = {
            "total_scored": len(results),
            "avg_overall": (
                sum(r.ensemble_overall for r in results) / len(results)
                if results
                else 0
            ),
            "avg_agreement": (
                sum(r.inter_judge_agreement for r in results) / len(results)
                if results
                else 0
            ),
            "by_pattern": {},
        }

        for r in results:
            if r.pattern_name not in summary["by_pattern"]:
                summary["by_pattern"][r.pattern_name] = {
                    "scores": [],
                    "agreements": [],
                }
            summary["by_pattern"][r.pattern_name]["scores"].append(r.ensemble_overall)
            summary["by_pattern"][r.pattern_name]["agreements"].append(
                r.inter_judge_agreement
            )

        # Compute per-pattern averages
        for pattern, data in summary["by_pattern"].items():
            data["avg_score"] = (
                sum(data["scores"]) / len(data["scores"]) if data["scores"] else 0
            )
            data["avg_agreement"] = (
                sum(data["agreements"]) / len(data["agreements"])
                if data["agreements"]
                else 0
            )
            data["n_scored"] = len(data["scores"])

        path = self.output_dir / "judge_summary.json"
        path.write_text(json.dumps(summary, indent=2))

    @staticmethod
    def _deserialize_ensemble(data: dict) -> EnsembleResult:
        """Deserialize a JSON dict into an EnsembleResult with nested dataclasses."""
        # Reconstruct nested JudgePassResult / CriterionVerdict objects
        passes = []
        for p in data.get("individual_passes", []):
            verdicts = [
                CriterionVerdict(**v) for v in p.get("verdicts", [])
            ]
            passes.append(JudgePassResult(
                judge_label=p["judge_label"],
                pass_number=p["pass_number"],
                verdicts=verdicts,
                dimension_scores=p["dimension_scores"],
                overall_score=p["overall_score"],
                raw_response=p.get("raw_response", ""),
            ))

        return EnsembleResult(
            query_id=data["query_id"],
            pattern_name=data["pattern_name"],
            individual_passes=passes,
            ensemble_overall=data["ensemble_overall"],
            ensemble_dimensions=data["ensemble_dimensions"],
            intra_judge_consistency=data.get("intra_judge_consistency", {}),
            inter_judge_agreement=data.get("inter_judge_agreement", 0.0),
            krippendorffs_alpha=data.get("krippendorffs_alpha", 0.0),
            per_dimension_agreement=data.get("per_dimension_agreement", {}),
            n_judges=data.get("n_judges", 0),
            n_passes_per_judge=data.get("n_passes_per_judge", 0),
            total_evaluations=data.get("total_evaluations", 0),
        )

    def load_all_results(self) -> list[EnsembleResult]:
        """Load all saved verdict files."""
        results: list[EnsembleResult] = []
        verdicts_dir = self.output_dir / "verdicts"
        if not verdicts_dir.exists():
            return results
        for pattern_dir in sorted(verdicts_dir.iterdir()):
            if pattern_dir.is_dir():
                for vf in sorted(pattern_dir.glob("*.json")):
                    try:
                        data = json.loads(vf.read_text())
                        results.append(self._deserialize_ensemble(data))
                    except (json.JSONDecodeError, TypeError, KeyError) as e:
                        logger.warning("verdict_load_failed", file=str(vf), error=str(e))
                        continue
        return results
